/**
 * 追击停步环 —— "追怪时停在哪里"与**攻击距离**的关系式（唯一实现）。
 *
 * ⚠ 这**不是**一个可以随便调的常数：环半径（世界单位）必须**严格小于**攻击距离
 * （服务端下发的 `shootingRange`），否则追击会彻底卡死。机理：
 *
 *   主循环每帧先判 `monsterEngaged = 距离 ≤ 攻击距离`（进攻击态 → 停步挥拳），
 *   再调 `updateMovement`，而后者一发现"已踏进环内"（`gap ≤ 0`）就**直接返回 false**。
 *   ⇒ 环半径 ≥ 攻击距离时，玩家会**停在环上**、永远进不了攻击态、
 *      既不移动也不攻击，900ms 后被"寻路受阻，放弃目标"判掉：
 *      **看得见怪、走不过去、也打不着。**
 *
 * 实测（用户 2026-09-15）：服务端把近战单手/徒手从 40 调成 30（`MELEE_RANGE_ONE_HAND`，
 * 上游 commit "调整近战武器攻击距离"），而环当时是硬编码 32（按 40 定的，
 * 注释还写着"距边界 8 的余量"）⇒ 空手与全部单手武器（30）卡死，只有双手（60）与
 * 远程（140~270）还正常 —— 症状表现为"新手弓箭手空手打不到怪"。
 *
 * 故环改成**由攻击距离推出**：攻击距离一动，环跟着动，两个数字不可能再漂开。
 *
 * ⚠ 也别把环取成"正好等于攻击距离"：落点由"本帧会越线就只走到环上"决定，
 * 会**精确落在环上** ⇒ 等于贴着判定边界停 —— 浮点抖动/怪物微动都会让它时真时假。
 * 留 20% 余量的意义就在这（30 → 24）。
 */

/** 环半径上限（世界单位）：攻击距离再大也只停到这儿，免得贴上怪身。远程/双手都落到它。 */
export const MONSTER_RING_CAP = 32;

/** 环半径 = 攻击距离 × 该比例（留余量，见文件头）。 */
const MONSTER_RING_RATIO = 0.8;

/**
 * 追怪时的停步环半径。
 *
 * 攻击距离缺失（`≤ 0`：快照未到 / 服务端没下发）时返回 0 —— **不造兜底值**：
 * 造一个"看起来正常"的环只会把"射程没拿到"伪装成正常追击（AGENTS #12），
 * 而卡住检测（`寻路受阻` 那条 warn）本来就是给这种情况用的。
 */
export function monsterStopRing(shootingRange: number): number {
  if (!(shootingRange > 0)) return 0;
  return Math.min(MONSTER_RING_CAP, shootingRange * MONSTER_RING_RATIO);
}
